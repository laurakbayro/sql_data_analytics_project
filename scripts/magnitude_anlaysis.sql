/*
===============================================================================
Magnitude Analysis
===============================================================================
Purpose:
    - To quantify data across different business dimensions.
    - To analyze the distribution of customers and products across categories.
    - To calculate average product costs and total revenue by category.
    - To identify the customers generating the highest revenue.
    - To analyze the distribution of sold quantities across countries.
    - To compare revenue aggregation using different LEFT JOIN directions.

SQL Functions and Clauses Used:
    - COUNT(): Counts non-NULL values.
    - AVG(): Calculates the average of numeric values.
    - SUM(): Calculates the total of numeric values.
    - GROUP BY: Groups rows sharing the same values.
    - ORDER BY: Sorts the results.
    - LEFT JOIN: Retains all rows from the left table.
===============================================================================
*/

-- Calculate the number of customers in each country
SELECT
    country,
    COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers DESC;

-- Calculate the number of customers by gender
SELECT
    gender,
    COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customers DESC;

-- Calculate the number of products in each category
SELECT
    category,
    COUNT(product_key) AS total_products
FROM gold.dim_products
GROUP BY category
ORDER BY total_products DESC;

-- Calculate the average product cost for each category
SELECT
    category,
    AVG(cost) AS avg_cost
FROM gold.dim_products
GROUP BY category
ORDER BY avg_cost DESC;

-- Calculate total revenue by category using the sales fact view as the starting point
SELECT
    p.category,
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
    ON p.product_key = f.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;

-- Compare join direction: start from products to retain categories without sales
SELECT
    p.category,
    SUM(f.sales_amount) AS total_revenue
FROM gold.dim_products p
LEFT JOIN gold.fact_sales f
    ON p.product_key = f.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;

-- Calculate total revenue generated by each customer
SELECT
    c.customer_key,
    c.first_name,
    c.last_name,
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
    ON c.customer_key = f.customer_key
GROUP BY
    c.customer_key,
    c.first_name,
    c.last_name
ORDER BY total_revenue DESC;

-- Calculate the total quantity of items sold in each country
SELECT
    c.country,
    SUM(f.quantity) AS total_sold_items
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
    ON c.customer_key = f.customer_key
GROUP BY c.country
ORDER BY total_sold_items DESC;
```
